#!/usr/bin/env python3
# Generates the PC-style Squeekboard layouts (fr, us, ara): same frame (Esc, Tab, Caps, Shift, Ctrl, Super, Alt,
# globe, AltGr, arrows, F1-F12 and navigation on AltGr), letters per language. Run after editing; commits the yaml.
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BOTTOM = 'Ctrl Super Alt Lang space AltGr Left Down Right'

LANGS = {
    'fr': {
        'base':  ['& é quot \'\' ( - è _ ç à ) =', 'a z e r t y u i o p ^ $', 'q s d f g h j k l m ù *', '< w x c v b n , ; : !'],
        'upper': ['1 2 3 4 5 6 7 8 9 0 ° +', 'A Z E R T Y U I O P ¨ £', 'Q S D F G H J K L M % µ', '> W X C V B N ? . / §'],
    },
    'us': {
        'base':  ['` 1 2 3 4 5 6 7 8 9 0 - =', 'q w e r t y u i o p [ ]', 'a s d f g h j k l ; \'\' \\', 'z x c v b n m , . /'],
        'upper': ['~ ! @ # $ % ^ & * ( ) _ +', 'Q W E R T Y U I O P { }', 'A S D F G H J K L : quot |', 'Z X C V B N M < > ?'],
    },
    'ara': {
        'base':  ['ذ 1 2 3 4 5 6 7 8 9 0 - =', 'ض ص ث ق ف غ ع ه خ ح ج د', 'ش س ي ب ل ا ت ن م ك ط \\', 'ئ ء ؤ ر لا ى ة و ز ظ'],
        'upper': ['ّ ! @ # $ % ^ & * ) ( _ +', 'َ ً ُ ٌ لإ إ ` ÷ × ؛ < >', 'ِ ٍ ] [ لأ أ ـ ، / : quot |', '~ ْ } { لآ آ \'\' , . ؟'],
    },
}

ALTGR = ['~ # { [ | ` \\ @ ] } €', 'F1 F2 F3 F4 F5 F6 F7 F8 F9 F10 F11 F12', 'â ê î ô û ë ï ü œ æ « »',
         'Home End PgUp PgDn Del Ins … – ±']

KEYS = '''buttons:
    quot:      { text: '"' }
    Esc:       { keysym: "Escape", label: "Esc" }
    Tab:       { keysym: "Tab", label: "Tab", outline: wide }
    BackSpace: { action: erase, icon: "edit-clear-symbolic", outline: wide }
    Return:    { keysym: "Return", icon: "key-enter", outline: wide }
    Caps:      { action: { locking: { lock_view: "upper", unlock_view: "base", looks_locked_from: [] } }, label: "Caps", outline: wide }
    Shift:     { action: { locking: { lock_view: "upper", unlock_view: "base" } }, icon: "key-shift", outline: wide }
    AltGr:     { action: { locking: { lock_view: "altgr", unlock_view: "base" } }, label: "AltGr", outline: wide }
    Ctrl:      { modifier: "Control", label: "Ctrl", outline: wide }
    Super:     { modifier: "Mod4", label: "Super", outline: wide }
    Alt:       { modifier: "Alt", label: "Alt", outline: wide }
    Lang:      { keysym: "XF86Keyboard", label: "🌐" }
    space:     { keysym: "space", label: " ", outline: space }
    Up:        { keysym: "Up", label: "↑" }
    Down:      { keysym: "Down", label: "↓" }
    Left:      { keysym: "Left", label: "←" }
    Right:     { keysym: "Right", label: "→" }
    Home:      { keysym: "Home", label: "Home" }
    End:       { keysym: "End", label: "End" }
    PgUp:      { keysym: "Page_Up", label: "PgUp" }
    PgDn:      { keysym: "Page_Down", label: "PgDn" }
    Del:       { keysym: "Delete", label: "Del" }
    Ins:       { keysym: "Insert", label: "Ins" }
''' + ''.join(f'    F{i}:{" " * (7 - len(str(i)))}{{ keysym: "F{i}" }}\n' for i in range(1, 13))


def view(rows):
    r1, r2, r3, r4 = rows
    return [f'Esc {r1} BackSpace', f'Tab {r2} Return', f'Caps {r3}', f'Shift {r4} Up', BOTTOM]


def layout(lang):
    views = {'base': view(LANGS[lang]['base']), 'upper': view(LANGS[lang]['upper']), 'altgr': view(ALTGR)}
    out = ['---', f'# Andromarchy: PC-style {lang} layout for Squeekboard (generated by gen-layouts.py).', 'outlines:',
           '    default: { width: 48, height: 32 }', '    wide:    { width: 72, height: 32 }',
           '    space:   { width: 260, height: 32 }', '', 'views:']
    for name, rows in views.items():
        out.append(f'    {name}:')
        out += [f"        - '{r}'" for r in rows]
    return '\n'.join(out) + '\n\n' + KEYS


for lang in LANGS:
    with open(os.path.join(HERE, f'{lang}_wide.yaml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(layout(lang))
