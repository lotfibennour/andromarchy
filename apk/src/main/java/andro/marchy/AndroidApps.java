package andro.marchy;

import android.content.BroadcastReceiver;
import android.content.Context;
import android.content.Intent;
import android.content.IntentFilter;
import android.content.pm.PackageManager;
import android.content.pm.ResolveInfo;
import android.util.Log;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/**
 * The Android apps as a "Mobile Apps" submenu, first in Omarchy's Apps menu (static JSONC children come before the
 * rows of its "apps" provider): a managed block of entries in the user menu
 * extension (~/.config/omarchy/extensions/omarchy-menu.jsonc, reloaded live by the shell; the rest of the file is the
 * user's). Each entry runs android-request "float <package>": the app opens in a floating window (see AndroidRequests).
 * Kept in sync on install/removal.
 */
final class AndroidApps extends BroadcastReceiver {
    private static final String TAG = "AndroidApps";
    private static final String BEGIN = "  // >>> Andromarchy: Android apps (generated by the app, edits here are replaced)";
    private static final String END = "  // <<< Andromarchy: Android apps";
    private final File menu;

    AndroidApps(Context ctx) {
        menu = new File(SessionService.rootfs(ctx), "root/.config/omarchy/extensions/omarchy-menu.jsonc");
    }

    void register(Context ctx) {
        IntentFilter f = new IntentFilter();
        f.addAction(Intent.ACTION_PACKAGE_ADDED);
        f.addAction(Intent.ACTION_PACKAGE_REMOVED);
        f.addAction(Intent.ACTION_PACKAGE_CHANGED);
        f.addDataScheme("package");
        ctx.registerReceiver(this, f);
        new Thread(() -> export(ctx)).start();
    }

    @Override
    public void onReceive(Context ctx, Intent intent) {
        new Thread(() -> export(ctx)).start();
    }

    private synchronized void export(Context ctx) {
        PackageManager pm = ctx.getPackageManager();
        Intent launcher = new Intent(Intent.ACTION_MAIN).addCategory(Intent.CATEGORY_LAUNCHER);
        List<String[]> apps = new ArrayList<>(); // {label, package}
        Set<String> seen = new HashSet<>();
        for (ResolveInfo ri : pm.queryIntentActivities(launcher, 0)) {
            String pkg = ri.activityInfo.packageName;
            if (!pkg.equals(ctx.getPackageName()) && seen.add(pkg))
                apps.add(new String[] {ri.loadLabel(pm).toString().replace('\n', ' ').trim(), pkg});
        }
        apps.sort((a, b) -> a[0].compareToIgnoreCase(b[0]));

        StringBuilder block = new StringBuilder(BEGIN).append('\n');
        block.append("  \"apps.mobile\": {\"icon\": \"󰀲\", \"label\": \"Mobile Apps\", \"aliases\": [\"android\", \"mobile\"]},\n");
        for (String[] a : apps)
            block.append("  \"apps.mobile.").append(a[1].replace('.', '_')).append("\": {\"icon\": \"󰀲\", \"label\": ")
                    .append(json(a[0])).append(", \"description\": ").append(json(a[1]))
                    .append(", \"action\": \"android-request float ").append(a[1]).append("\"},\n");
        block.append(END);

        try {
            String text = menu.exists() ? new String(Files.readAllBytes(menu.toPath())) : "{\n}\n";
            int b = text.indexOf(BEGIN), e = text.indexOf(END);
            if (b >= 0 && e > b)
                text = text.substring(0, b) + text.substring(e + END.length() + (text.startsWith("\n", e + END.length()) ? 1 : 0));
            int close = text.lastIndexOf('}'); // entries go inside the top-level object
            if (close < 0)
                return;
            text = text.substring(0, close) + block + "\n" + text.substring(close);
            menu.getParentFile().mkdirs();
            File tmp = new File(menu.getParent(), ".omarchy-menu.jsonc");
            try (FileWriter w = new FileWriter(tmp)) {
                w.write(text);
            }
            tmp.renameTo(menu);
        } catch (IOException ex) {
            Log.w(TAG, "menu export", ex);
        }
    }

    private static String json(String s) {
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
